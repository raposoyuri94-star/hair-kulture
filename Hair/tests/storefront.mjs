import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'msedge', headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}, colorScheme:'light'});
const errors=[];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://localhost:5176/', {waitUntil:'networkidle'});
await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
assert.equal(await page.locator('.product-card').count(),5);
await page.getByRole('button',{name:'Cacheados',exact:true}).click();
assert.equal(await page.locator('.product-card').count(),1);
await page.getByRole('button',{name:'Todos',exact:true}).click();
await page.getByRole('button',{name:'Guardar nos favoritos: Protagonista',exact:true}).click();
await page.getByRole('button',{name:'Favoritos (1)',exact:true}).click();
assert.equal(await page.locator('.product-card').count(),1);
await page.getByRole('button',{name:'Ver Protagonista',exact:true}).click();
await page.getByRole('dialog').getByRole('button',{name:'Adicionar ao carrinho',exact:true}).click();
await page.getByRole('button',{name:'Abrir carrinho, 1 artigos'}).click();
await page.getByRole('button',{name:'Aumentar quantidade de Protagonista'}).click();
assert.match(await page.locator('.subtotal').innerText(),/370/);
await page.getByRole('button',{name:'Simular encomenda'}).click();
assert.match(await page.locator('.checkout-notice').innerText(),/nenhuma encomenda foi efetuada/);
await page.keyboard.press('Escape');
await page.reload({waitUntil:'networkidle'});
assert.equal(await page.getByRole('button',{name:'Abrir carrinho, 2 artigos'}).count(),1);
await page.getByRole('button',{name:'Pesquisar produtos',exact:true}).click();
await page.getByPlaceholder('Pesquisar por estilo ou nome...').fill('not-a-wig');
await page.getByRole('heading',{name:'Nenhum produto encontrado.'}).waitFor();
await page.getByRole('button',{name:'Fechar pesquisa'}).click();
await page.getByRole('button',{name:'Descubra o seu cabelo ideal'}).click();
await page.getByRole('dialog').getByRole('button',{name:/Um visual liso e elegante/}).click();
assert.equal(await page.locator('.product-card').count(),2);
await page.getByRole('button',{name:'Todos',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.getByRole('button',{name:'Abrir ou fechar menu'}).click();
await page.getByRole('navigation',{name:'Navegação móvel'}).getByRole('button',{name:'Cacheados',exact:true}).click();
assert.equal(await page.locator('.product-card').count(),1);
await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
await page.waitForTimeout(300);
assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).backgroundColor),'rgb(255, 255, 255)');
assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).color),'rgb(53, 35, 44)');
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'artifacts/mobile-dark.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
assert.deepEqual(errors,[]);
await page.getByRole('button',{name:'Tissagens',exact:true}).click();
assert.equal(await page.locator('.product-card').count(),1);
await page.getByRole('button',{name:'Ver Kit de Tissagens Onduladas',exact:true}).click();
await page.getByRole('dialog').getByRole('button',{name:'Adicionar ao carrinho',exact:true}).click();
await page.getByRole('button',{name:'Abrir carrinho, 3 artigos'}).click();
assert.match(await page.locator('.bag-items').innerText(),/Kit de Tissagens Onduladas/);
assert.match(await page.locator('.subtotal').innerText(),/515/);
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Perucas',exact:true}).click();
assert.equal(await page.locator('.product-card').count(),4);
await browser.close();
console.log('PASS: filters, favorites, product dialog, bag quantities, persistence, checkout preview, search, style guide, mobile navigation, light/dark layouts; no browser errors.');
